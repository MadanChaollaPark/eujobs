/** Deliberately synthetic showcase records. They never claim source verification or accept applications. */
export function createSampleListings(now = new Date()): Listing[] {
  const base = (
    kind: Listing['kind'],
    index: number,
    title: string,
    org: number,
    location: string,
    topic: string,
    summary: string,
  ): Listing => {
    const [organization, initials, color] = organizations[org];
    const id = `sample-${kind}-${String(index + 1).padStart(2, '0')}`;
    const createdAt = new Date(now.getTime() - (index % 12) * 86400000 - 3600000).toISOString();
    return {
      id,
      slug: `${slugify(title)}-${kind}-${index + 1}`,
      kind,
      title,
      organization,
      organizationId: `sample-org-${org + 1}`,
      initials,
      color,
      location,
      country: countryByCity[location],
      topic,
      summary,
      description: `${summary}\n\nThis is a fictional sample ${kind === 'job' ? 'role' : 'event'}, created to demonstrate EUJobs. ${organization} is a fictional organization; there is no live application or registration.\n\n${kind === 'job' ? 'The sample role involves following policy developments, preparing clear written analysis and collaborating with people across different areas of expertise. It illustrates the kind of purposeful, practical work you can discover here.' : 'This sample programme includes an expert conversation, an open discussion and time to exchange ideas. It illustrates the kinds of thoughtful, accessible events you can discover here.'}\n\n${kind === 'job' ? 'We value curiosity, good judgement and a collaborative approach. This example is written to show the scope of the work, the employment terms and the application deadline in one place.' : 'The event details below are for demonstration only. Save it to explore your account or download its sample calendar invitation.'}`,
      status: 'published',
      ownerId: null,
      version: 1,
      createdAt,
      updatedAt: createdAt,
      publishedAt: createdAt,
      isSample: true,
      featured: index < (kind === 'job' ? 4 : 3),
      sourceUrl: null,
      sourceCheckedAt: null,
      url: null,
      employmentType: null,
      seniority: null,
      workMode: null,
      salaryMin: null,
      salaryMax: null,
      salaryPeriod: null,
      deadline: null,
      startsAt: null,
      endsAt: null,
      timezone:
        location === 'Remote'
          ? 'Europe/Brussels'
          : location === 'Amsterdam'
            ? 'Europe/Amsterdam'
            : location === 'Berlin'
              ? 'Europe/Berlin'
              : location === 'Luxembourg'
                ? 'Europe/Luxembourg'
                : location === 'Strasbourg'
                  ? 'Europe/Paris'
                  : 'Europe/Brussels',
      eventType: null,
      venue: null,
      price: null,
      rejectionReason: null,
    };
  };
  const jobs = jobSeeds.map(
    ([title, org, location, topic, mode, type, seniority, salary, summary], index) => ({
      ...base('job', index, title, org, location, topic, summary),
      employmentType: type,
      seniority,
      workMode: mode,
      salaryMin: salary,
      salaryMax: salary === null ? null : type === 'Traineeship' ? salary : salary + 8000,
      salaryPeriod:
        salary === null ? null : type === 'Traineeship' ? ('month' as const) : ('year' as const),
      deadline: offset(now, 6 + (index % 24), 22),
    }),
  );
  const events = eventSeeds.map(([title, org, city, topic, type, day, price, summary], index) => ({
    ...base('event', index, title, org, city, topic, summary),
    startsAt: offset(now, day, type === 'Networking' ? 16 : 9),
    endsAt: offset(now, day, type === 'Networking' ? 19 : type === 'Conference' ? 16 : 12),
    eventType: type,
    price,
    venue:
      city === 'Remote' ? 'Online · sample event' : `${organizations[org][0]} Forum · sample venue`,
  }));
  return [...jobs, ...events];
}
